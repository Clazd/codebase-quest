import type { Change, FixtureDefinition, Person } from "./types.ts";

// Fixtures whose contents can't live as normal text files in this repository
// (binary data, CRLF, non-UTF-8, symlinks, a 2 MB file, a .env), so they are
// generated here, byte by byte. Everything is deterministic.

const text = (s: string): Uint8Array => new TextEncoder().encode(s);
const file = (path: string, contents: Uint8Array | string): Change => ({
  kind: "file",
  path,
  contents: typeof contents === "string" ? text(contents) : contents,
});

const WEIRD_AUTHOR: Person = { name: "Wren Odd", email: "wren@example.com" };

/** Exactly 2 MiB or a little more of generated JavaScript. */
function generatedBundle(): string {
  const lines = ["// @generated by the weird-repo build. Do not edit.", ""];
  let size = lines.join("\n").length;
  for (let i = 1; size < 2 * 1024 * 1024; i++) {
    const line = `export const value_${String(i).padStart(6, "0")} = ${i};`;
    lines.push(line);
    size += line.length + 1;
  }
  return `${lines.join("\n")}\n`;
}

/** 1 KiB of binary data with a PNG-like signature and NUL bytes. */
function binaryBlob(): Uint8Array {
  const bytes = new Uint8Array(1024);
  bytes.set([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  for (let i = 8; i < bytes.length; i++) bytes[i] = (i * 31) % 256;
  return bytes;
}

export function weirdRepo(): FixtureDefinition {
  const deepPath = `${Array.from({ length: 10 }, (_, i) => `level${i + 1}`).join("/")}/deep.ts`;
  return {
    name: "weird-repo",
    description:
      "Every awkward thing a real repository can contain: binary data, a symlink, a 2 MB generated file, " +
      "invalid syntax, non-UTF-8 text, an empty file, CRLF endings, 10 nested folders and a .env with a fake " +
      "secret that must never be read.",
    commits: [
      {
        message: "chore: start the weird repo",
        author: WEIRD_AUTHOR,
        date: "2025-04-01T12:00:00+00:00",
        changes: [
          file(
            "README.md",
            "# weird-repo\n\nA fixture full of edge cases. The analyzer must finish and report each one.\n",
          ),
          // biome-ignore lint/suspicious/noTemplateCurlyInString: this is fixture source code, not a template
          file("src/index.ts", "export function hello(name: string): string {\n  return `Hello, ${name}`;\n}\n"),
          file("src/broken.ts", "export function broken( {\n  return ;\n\nconst = 3\n"),
          // "// café" encoded as Latin-1: 0xE9 is not valid UTF-8 on its own.
          file("src/latin1.ts", Uint8Array.from([...text("// caf"), 0xe9, ...text("\nexport const x = 1;\n")])),
          file("src/empty.ts", new Uint8Array(0)),
          file(
            "src/crlf.ts",
            "export const a = 1;\r\nexport const b = 2;\r\n\r\nexport function sum(): number {\r\n  return a + b;\r\n}\r\n",
          ),
          file(deepPath, "export const depth = 10;\n"),
          file("assets/blob.bin", binaryBlob()),
          // A fake secret. Analyzers must skip .env files and never read them.
          file(".env", "CQ_FAKE_SECRET=not-a-real-secret-cq-fixture-0000\nCQ_FAKE_TOKEN=also-fake-0000\n"),
          { kind: "symlink", path: "docs/readme-link.md", target: "../README.md" },
        ],
      },
      {
        message: "build: commit the generated bundle",
        author: WEIRD_AUTHOR,
        date: "2025-04-02T12:00:00+00:00",
        changes: [file("generated/bundle.generated.js", generatedBundle())],
      },
    ],
  };
}

