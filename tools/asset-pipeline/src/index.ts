export function pixelize(source: PNG, alphaThreshold = 128): PNG {
  const image = new PNG({ width: source.width, height: source.height });
  for (let i = 0; i < source.data.length; i += 4) {
    if ((source.data[i + 3] ?? 0) < alphaThreshold) continue;
    let nearest = PALETTE[0] as number[];
    let distance = Number.POSITIVE_INFINITY;
    for (const color of PALETTE) {
      const d = color.reduce((sum, channel, c) => sum + (channel - (source.data[i + c] ?? 0)) ** 2, 0);
      if (d < distance) {
        distance = d;
        nearest = color;
      }
    }
    image.data.set([...nearest, 255], i);
  }
  const opaque = Buffer.from(image.data);
  for (let y = 0; y < image.height; y++)
    for (let x = 0; x < image.width; x++) {
      const i = (y * image.width + x) * 4;
      if (opaque[i + 3] !== 0) continue;
      if (
        [
          [x - 1, y],
          [x + 1, y],
          [x, y - 1],
          [x, y + 1],
        ].some(
          ([nx = -1, ny = -1]) =>
            nx >= 0 &&
            ny >= 0 &&
            nx < image.width &&
            ny < image.height &&
            opaque[(ny * image.width + nx) * 4 + 3] === 255,
        )
      ) {
        image.data.set([...(PALETTE[0] as number[]), 255], i);
      }
    }
  return image;
}

export function packAtlas(sprites: Record<string, PNG>, columns = 8) {
  const entries = Object.entries(sprites).sort(([a], [b]) => a.localeCompare(b, "en"));
  if (!entries.length || !Number.isInteger(columns) || columns < 1)
    throw new Error("Atlas needs sprites and positive columns");
  const width = entries[0]?.[1].width ?? 0;
  const height = entries[0]?.[1].height ?? 0;
  const image = new PNG({ width: width * columns, height: height * Math.ceil(entries.length / columns) });
  const frames: Record<
    string,
    {
      frame: { x: number; y: number; w: number; h: number };
      rotated: boolean;
      trimmed: boolean;
      spriteSourceSize: { x: number; y: number; w: number; h: number };
      sourceSize: { w: number; h: number };
    }
  > = {};
  entries.forEach(([name, sprite], index) => {
    if (sprite.width !== width || sprite.height !== height) throw new Error("All atlas frames must be the same size");
    const x = (index % columns) * width;
    const y = Math.floor(index / columns) * height;
    PNG.bitblt(sprite, image, 0, 0, width, height, x, y);
    frames[name] = {
      frame: { x, y, w: width, h: height },
      rotated: false,
      trimmed: false,
      spriteSourceSize: { x: 0, y: 0, w: width, h: height },
      sourceSize: { w: width, h: height },
    };
  });
  return {
    image,
    atlas: { frames, meta: { image: "sprites.png", size: { w: image.width, h: image.height }, scale: "1" } },
  };
}

/** Six 16px tiles, generated by a fixed coordinate hash with no RNG state. */
export function tileSample(): PNG {
  const image = new PNG({ width: 96, height: 16 });
  for (let tile = 0; tile < 6; tile++)
    for (let y = 0; y < 16; y++)
      for (let x = 0; x < 16; x++) {
        const hash = ((x * 73 + y * 151 + tile * 47) ^ (x * y * 31)) >>> 0;
        let color: number;
        if (tile < 3) color = 9 + (hash % 9 === 0 ? 2 : tile % 2);
        else if (tile === 3) color = hash % 7 === 0 ? 27 : 28;
        else if (tile === 4) color = (y + (x >> 2)) % 5 === 0 ? 16 : 14;
        else color = y % 6 === 0 || (x + (Math.floor(y / 6) % 2) * 8) % 16 === 0 ? 1 : 3;
        image.data.set([...(PALETTE[color] as number[]), 255], (y * image.width + tile * 16 + x) * 4);
      }
  return image;
}
